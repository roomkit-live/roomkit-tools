"""Prove that a built distribution contains only tracked sources and build output.

Maturin packs files from the working tree, including untracked and ignored
ones. Each archived file must therefore be a file git tracks, found at its
repository path or relative to the Python project directory, or an item that
the build itself generates.
"""

from __future__ import annotations

import subprocess
import tarfile
import zipfile
from pathlib import Path, PurePosixPath

# Written by maturin into every source distribution.
GENERATED_SDIST = {"PKG-INFO"}
# Written by maturin into every wheel's .dist-info directory.
GENERATED_DIST_INFO = {"METADATA", "WHEEL", "RECORD"}


def tracked_files(root: Path) -> set[str]:
    listing = subprocess.check_output(["git", "ls-files", "-z"], cwd=root, text=True)
    return set(listing.split("\0")) - {""}


def is_tracked(path: str, tracked: set[str], sources: list[str]) -> bool:
    """Whether path names a tracked file below one of the source directories."""
    return any(str(PurePosixPath(source, path)) in tracked for source in sources)


def check_sdist(archive_path: Path, root: Path, project: str = ".") -> None:
    """Refuse an sdist file that is neither tracked nor generated by maturin."""
    tracked = tracked_files(root)
    with tarfile.open(archive_path) as archive:
        names = [member.name for member in archive.getmembers() if member.isfile()]
    prefixes = {name.split("/", 1)[0] for name in names}
    assert len(prefixes) == 1, prefixes
    unexpected = [
        relative
        for relative in (name.split("/", 1)[1] for name in names)
        if relative not in GENERATED_SDIST and not is_tracked(relative, tracked, [".", project])
    ]
    assert not unexpected, f"{archive_path.name} contains untracked files: {unexpected}"


def check_wheel(
    archive_path: Path, root: Path, package: str, project: str = ".", extra: tuple[str, ...] = ()
) -> None:
    """Refuse a wheel file outside the expected prefixes or not built from tracked files.

    Allowed: the import package (tracked Python sources and one native module),
    generated .dist-info metadata and SBOMs, declared license files and the
    project files listed in extra.
    """
    tracked = tracked_files(root)
    with zipfile.ZipFile(archive_path) as archive:
        names = [name for name in archive.namelist() if not name.endswith("/")]
    dist_info = next(name.split("/", 1)[0] for name in names if name.endswith(".dist-info/WHEEL"))
    native = [name for name in names if is_native_module(name, package)]
    assert len(native) == 1, native
    unexpected = []
    for name in names:
        top, _, relative = name.partition("/")
        if name in native or (top == dist_info and is_generated(relative)):
            continue
        if top == dist_info and relative.startswith("licenses/"):
            allowed = is_tracked(relative.removeprefix("licenses/"), tracked, [project])
        elif top == package:
            allowed = is_tracked(name, tracked, [f"{project}/python"])
        else:
            allowed = name in extra and is_tracked(name, tracked, [project])
        if not allowed:
            unexpected.append(name)
    assert not unexpected, f"{archive_path.name} contains unexpected files: {unexpected}"


def is_native_module(name: str, package: str) -> bool:
    path = PurePosixPath(name)
    return (
        str(path.parent) == package
        and path.name.startswith("_native.")
        and path.suffix in (".so", ".pyd")
    )


def is_generated(relative: str) -> bool:
    path = PurePosixPath(relative)
    return relative in GENERATED_DIST_INFO or (
        str(path.parent) == "sboms" and path.name.endswith(".cyclonedx.json")
    )
